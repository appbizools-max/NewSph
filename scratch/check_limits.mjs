const normalizeToYMD = (raw) => {
  if (!raw) return '';
  let val = raw;
  if (typeof val === 'object') {
    if (typeof val.toDate === 'function') val = val.toDate();
    else if (typeof val.seconds === 'number') val = new Date(val.seconds * 1000);
  }
  if (val instanceof Date) {
    if (!isNaN(val.getTime())) {
      const y = val.getFullYear();
      const m = String(val.getMonth() + 1).padStart(2, '0');
      const d = String(val.getDate()).padStart(2, '0');
      return `${y}-${m}-${d}`;
    }
    return '';
  }
  const str = String(val).trim();
  if (!str || str === '[object Object]') return '';
  const isoMatch = str.match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})/);
  if (isoMatch) return `${isoMatch[1]}-${isoMatch[2].padStart(2, '0')}-${isoMatch[3].padStart(2, '0')}`;
  const ddmmyyyyMatch = str.match(/^(\d{1,2})[\/-](\d{1,2})[\/-](\d{4})/);
  if (ddmmyyyyMatch) return `${ddmmyyyyMatch[3]}-${ddmmyyyyMatch[2].padStart(2, '0')}-${ddmmyyyyMatch[1].padStart(2, '0')}`;
  return '';
};

async function checkLimits() {
  const qPat = query(collection(db, 'allpatients'), limit(1500));
  const snap = await getDocs(qPat);
  console.log(`Received ${snap.size} allpatients with limit(1500)`);
  let octCount = 0;
  const monthDist = {};
  snap.forEach(doc => {
    const d = doc.data();
    const ymd = normalizeToYMD(d.paymentCollectedAt || d.createdAt || d.date);
    const m = ymd ? ymd.slice(0, 7) : 'NO_DATE';
    monthDist[m] = (monthDist[m] || 0) + 1;
    if (ymd?.startsWith('2026-10')) octCount++;
  });
  console.log('Month distribution with limit(1500):', monthDist);
  console.log('October count with limit(1500):', octCount);
}

checkLimits().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });
